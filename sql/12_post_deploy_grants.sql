-- =============================================================================
-- DOC_INTEL: Post-Deployment Grants
-- File: sql/12_post_deploy_grants.sql
-- Description: RBAC grants and caller privileges applied after all objects exist.
-- Run as: DOC_INTEL_ADMIN (owns the database)
-- =============================================================================

USE ROLE DOC_INTEL_ADMIN;
USE WAREHOUSE DOC_INTEL_QUERY_WH;

-- =============================================================================
-- SECTION 1: Caller Privileges for SPCS Restricted Caller's Rights
-- DOC_INTEL_ADMIN owns the SPCS service. These grants allow it to access
-- objects on behalf of the logged-in user.
-- =============================================================================

-- Database-level
GRANT ALL CALLER PRIVILEGES ON DATABASE DOC_INTEL TO ROLE DOC_INTEL_ADMIN;

-- Schema-level
GRANT ALL INHERITED CALLER PRIVILEGES ON ALL SCHEMAS IN DATABASE DOC_INTEL TO ROLE DOC_INTEL_ADMIN;

-- Table/view/DT-level
GRANT ALL INHERITED CALLER PRIVILEGES ON ALL TABLES IN DATABASE DOC_INTEL TO ROLE DOC_INTEL_ADMIN;
GRANT ALL INHERITED CALLER PRIVILEGES ON ALL VIEWS IN DATABASE DOC_INTEL TO ROLE DOC_INTEL_ADMIN;
GRANT ALL INHERITED CALLER PRIVILEGES ON ALL DYNAMIC TABLES IN DATABASE DOC_INTEL TO ROLE DOC_INTEL_ADMIN;

-- Stages (presigned URL access for document retrieval)
GRANT ALL INHERITED CALLER PRIVILEGES ON ALL STAGES IN DATABASE DOC_INTEL TO ROLE DOC_INTEL_ADMIN;

-- Procedures
GRANT INHERITED CALLER USAGE ON ALL PROCEDURES IN DATABASE DOC_INTEL TO ROLE DOC_INTEL_ADMIN;

-- Warehouse (app queries)
GRANT CALLER USAGE ON WAREHOUSE DOC_INTEL_QUERY_WH TO ROLE DOC_INTEL_ADMIN;

-- Cortex AI functions
GRANT CALLER USE AI FUNCTIONS ON ACCOUNT TO ROLE DOC_INTEL_ADMIN;

-- Agent caller usage
GRANT CALLER USAGE ON AGENT DOC_INTEL.SERVICES.DOC_INTELLIGENCE_AGENT TO ROLE DOC_INTEL_ADMIN;

-- Semantic View caller usage (required for agent's analyst tool)
GRANT ALL CALLER PRIVILEGES ON SEMANTIC VIEW DOC_INTEL.SERVICES.DOCUMENT_ANALYTICS_SV TO ROLE DOC_INTEL_ADMIN;

-- Cortex Search caller usage
GRANT CALLER USAGE ON CORTEX SEARCH SERVICE DOC_INTEL.SERVICES.DOC_SEARCH_SVC TO ROLE DOC_INTEL_ADMIN;
GRANT CALLER USAGE ON CORTEX SEARCH SERVICE DOC_INTEL.SERVICES.DOC_PAGE_SEARCH_SVC TO ROLE DOC_INTEL_ADMIN;

-- SNOWFLAKE database. Cortex functions in caller's-rights sessions are covered by
-- CALLER USE AI FUNCTIONS above; SNOWFLAKE is a shared database, so schema- and
-- function-level caller grants on SNOWFLAKE.CORTEX are not allowed.
GRANT CALLER USAGE ON DATABASE SNOWFLAKE TO ROLE DOC_INTEL_ADMIN;

-- =============================================================================
-- SECTION 2: Standard RBAC Object Grants
-- DOC_INTEL_ADMIN owns everything, grants to child roles.
-- =============================================================================

-- Database and schema USAGE
GRANT USAGE ON DATABASE DOC_INTEL TO ROLE DOC_INTEL_USER;
GRANT USAGE ON DATABASE DOC_INTEL TO ROLE DOC_INTEL_PIPELINE;
GRANT USAGE ON SCHEMA DOC_INTEL.DATA TO ROLE DOC_INTEL_USER;
GRANT USAGE ON SCHEMA DOC_INTEL.DATA TO ROLE DOC_INTEL_PIPELINE;
GRANT USAGE ON SCHEMA DOC_INTEL.SERVICES TO ROLE DOC_INTEL_USER;
GRANT USAGE ON SCHEMA DOC_INTEL.SERVICES TO ROLE DOC_INTEL_PIPELINE;
GRANT USAGE ON SCHEMA DOC_INTEL.TELEMETRY TO ROLE DOC_INTEL_USER;
GRANT USAGE ON SCHEMA DOC_INTEL.TELEMETRY TO ROLE DOC_INTEL_PIPELINE;
GRANT USAGE ON SCHEMA DOC_INTEL.ADMIN TO ROLE DOC_INTEL_USER;
GRANT USAGE ON SCHEMA DOC_INTEL.ADMIN TO ROLE DOC_INTEL_PIPELINE;
GRANT USAGE ON SCHEMA DOC_INTEL.APP TO ROLE DOC_INTEL_USER;
GRANT USAGE ON SCHEMA DOC_INTEL.APP_SERVICE TO ROLE DOC_INTEL_USER;

-- Warehouse USAGE
GRANT USAGE ON WAREHOUSE DOC_INTEL_QUERY_WH TO ROLE DOC_INTEL_USER;
GRANT USAGE ON WAREHOUSE DOC_INTEL_QUERY_WH TO ROLE DOC_INTEL_PIPELINE;
GRANT USAGE ON WAREHOUSE DOC_INTEL_WH TO ROLE DOC_INTEL_PIPELINE;

-- DATA schema — users get SELECT on specific tables (NOT document_catalog — use APP view)
GRANT SELECT ON TABLE DOC_INTEL.DATA.ingestion_registry TO ROLE DOC_INTEL_USER;
GRANT SELECT ON TABLE DOC_INTEL.DATA.parsed_documents TO ROLE DOC_INTEL_USER;
GRANT SELECT ON TABLE DOC_INTEL.DATA.classified_documents TO ROLE DOC_INTEL_USER;
GRANT SELECT ON TABLE DOC_INTEL.DATA.document_attributes TO ROLE DOC_INTEL_USER;
GRANT SELECT ON TABLE DOC_INTEL.DATA.document_pages TO ROLE DOC_INTEL_USER;
GRANT SELECT ON ALL VIEWS IN SCHEMA DOC_INTEL.DATA TO ROLE DOC_INTEL_USER;
-- Pipeline gets INSERT/SELECT/UPDATE (not DELETE/TRUNCATE/ALTER)
GRANT SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA DOC_INTEL.DATA TO ROLE DOC_INTEL_PIPELINE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA DOC_INTEL.DATA TO ROLE DOC_INTEL_USER;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA DOC_INTEL.DATA TO ROLE DOC_INTEL_USER;

-- APP schema: the app reads these views as the signed-in user
GRANT SELECT ON ALL VIEWS IN SCHEMA DOC_INTEL.APP TO ROLE DOC_INTEL_USER;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA DOC_INTEL.APP TO ROLE DOC_INTEL_USER;

-- SERVICES schema — search, agent, semantic view
GRANT USAGE ON ALL CORTEX SEARCH SERVICES IN SCHEMA DOC_INTEL.SERVICES TO ROLE DOC_INTEL_USER;
GRANT USAGE ON AGENT DOC_INTEL.SERVICES.DOC_INTELLIGENCE_AGENT TO ROLE DOC_INTEL_USER;
GRANT SELECT, REFERENCES ON SEMANTIC VIEW DOC_INTEL.SERVICES.DOCUMENT_ANALYTICS_SV TO ROLE DOC_INTEL_USER;

-- TELEMETRY schema — read for users, write for pipeline
GRANT SELECT ON ALL TABLES IN SCHEMA DOC_INTEL.TELEMETRY TO ROLE DOC_INTEL_USER;
GRANT SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA DOC_INTEL.TELEMETRY TO ROLE DOC_INTEL_PIPELINE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA DOC_INTEL.TELEMETRY TO ROLE DOC_INTEL_USER;

-- ADMIN schema — specific table grants for user-facing features
GRANT SELECT ON ALL TABLES IN SCHEMA DOC_INTEL.ADMIN TO ROLE DOC_INTEL_USER;
GRANT SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA DOC_INTEL.ADMIN TO ROLE DOC_INTEL_PIPELINE;
GRANT INSERT, SELECT, DELETE ON DOC_INTEL.ADMIN.DOCUMENT_BOOKMARKS TO ROLE DOC_INTEL_USER;
GRANT INSERT, SELECT ON DOC_INTEL.ADMIN.SEARCH_FEEDBACK TO ROLE DOC_INTEL_USER;
GRANT INSERT, SELECT ON DOC_INTEL.ADMIN.EXTRACTION_OVERRIDES TO ROLE DOC_INTEL_USER;
GRANT INSERT, SELECT, UPDATE, DELETE ON DOC_INTEL.ADMIN.SAVED_SEARCHES TO ROLE DOC_INTEL_USER;
GRANT INSERT, SELECT ON DOC_INTEL.TELEMETRY.AGENT_AUDIT_LOG TO ROLE DOC_INTEL_USER;

-- Stage read access for pipeline
GRANT READ ON STAGE DOC_INTEL.DATA.DOC_STAGE TO ROLE DOC_INTEL_PIPELINE;
-- Readers open cited documents from the app
GRANT READ ON STAGE DOC_INTEL.DATA.DOC_STAGE TO ROLE DOC_INTEL_USER;
GRANT READ ON STAGE DOC_INTEL.DATA.SAMPLE_STAGE TO ROLE DOC_INTEL_PIPELINE;
GRANT READ ON STAGE DOC_INTEL.DATA.METADATA_STAGE TO ROLE DOC_INTEL_PIPELINE;

-- Cortex AI (granted by provision.sh via ACCOUNTADMIN — listed here for reference)
-- GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE DOC_INTEL_USER;
-- GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE DOC_INTEL_PIPELINE;

-- =============================================================================
-- SECTION 3: Role Hierarchy (idempotent)
-- =============================================================================

GRANT ROLE DOC_INTEL_USER     TO ROLE DOC_INTEL_ADMIN;
-- NOTE: DOC_INTEL_PIPELINE must NOT be granted to DOC_INTEL_ADMIN (RAP bypass issue)
-- GRANT ROLE DOC_INTEL_PIPELINE TO ROLE DOC_INTEL_ADMIN;

-- =============================================================================
-- SECTION 4: Verification
-- =============================================================================

SHOW CALLER GRANTS ON DATABASE DOC_INTEL;

-- =============================================================================
-- SECTION 5: App access. DOC_INTEL_ADMIN owns the app; DOC_INTEL_USER can open it.
-- =============================================================================
GRANT USAGE ON APPLICATION SERVICE DOC_INTEL.APP_SERVICE.DOC_INTEL_APP TO ROLE DOC_INTEL_USER;

SELECT 'Post-deploy grants completed' AS status,
       CURRENT_TIMESTAMP() AS applied_at,
       CURRENT_ROLE() AS applied_by;
